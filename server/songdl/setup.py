"""Renders slskd's config file (slskd/slskd.yml) from config.yaml.

Runs as a one-shot container before slskd starts, so config.yaml stays the
only file users edit. The API key and the slskd web UI password are generated
once and kept across runs.
"""

import secrets

import yaml

from .config import Config

# Paths inside the slskd container
SLSKD_DOWNLOADS = '/app/downloads'
SLSKD_INCOMPLETE = '/app/incomplete'

HEADER = '# Generated by Song-DL from config.yaml on every start. Edit config.yaml instead.\n'


def _existing(path):
    try:
        data = yaml.safe_load(path.read_text(encoding='utf-8')) or {}
        auth = data['web']['authentication']
        return auth['api_keys']['songdl']['key'], auth['password']
    except (OSError, yaml.YAMLError, KeyError, TypeError):
        return None, None


def api_key(cfg: Config):
    key, _ = _existing(cfg.slskd_dir / 'slskd.yml')
    if not key:
        raise RuntimeError(f'No API key in {cfg.slskd_dir / "slskd.yml"}. Run the setup step first.')
    return key


def render(cfg: Config):
    path = cfg.slskd_dir / 'slskd.yml'
    key, ui_password = _existing(path)
    key = key or secrets.token_urlsafe(32)
    ui_password = ui_password or secrets.token_urlsafe(16)
    day = 24 * 60  # slskd retention values are in minutes

    data = {
        'headless': True,  # no slskd web UI; Song-DL only uses its API
        'remote_configuration': False,
        'flags': {'no_version_check': True},
        'directories': {'downloads': SLSKD_DOWNLOADS, 'incomplete': SLSKD_INCOMPLETE},
        'shares': {'directories': [SLSKD_DOWNLOADS] if cfg.share else []},
        'transfers': {'download': {'destination': {'exists': 'rename'}}},
        'retention': {
            'search': 60,
            'transfers': {'download': {'succeeded': 60, 'errored': 60, 'cancelled': 5, 'failed': 60}},
            # Song-DL deletes old downloads itself. slskd's own file cleanup is left off:
            # it would also delete the files saved into server folders.
            'files': {'incomplete': day},
        },
        'web': {
            'authentication': {
                'disabled': False,
                'username': 'songdl',
                'password': ui_password,
                'api_keys': {'songdl': {'key': key, 'role': 'readwrite', 'cidr': '0.0.0.0/0,::/0'}},
            },
        },
        'soulseek': {
            'address': cfg.address,
            'port': cfg.port,
            'username': cfg.username,
            'password': cfg.password,
            'description': cfg.description or 'Song-DL',
            'listen_port': cfg.listen_port,
        },
    }

    cfg.slskd_dir.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix('.tmp')
    tmp.write_text(HEADER + yaml.safe_dump(data, sort_keys=False, allow_unicode=True), encoding='utf-8')
    tmp.chmod(0o600)
    tmp.replace(path)
    return path
